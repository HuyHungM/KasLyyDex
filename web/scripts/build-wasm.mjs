// Reproducible wasm-bindgen build: cargo (wasm32) -> wasm-bindgen CLI ->
// content-hashed public asset + generated TS/ESM entry. Nothing here is committed;
// CI runs `npm run build:wasm` before `next build`.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const webDir = fileURLToPath(new URL("..", import.meta.url));
const repoDir = fileURLToPath(new URL("../..", import.meta.url));
const generatedDir = join(webDir, "generated", "reader-wasm");
const publicDir = join(webDir, "public", "wasm");

function run(command, args) {
  const result = spawnSync(command, args, { stdio: "inherit" });
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed with code ${result.status}`);
  }
}

function findWasmBindgen() {
  const explicit = process.env.WASM_BINDGEN_BIN;
  if (explicit && existsSync(explicit)) return explicit;
  const cargoBin = join(process.env.USERPROFILE ?? process.env.HOME ?? "", ".cargo", "bin");
  for (const name of ["wasm-bindgen.exe", "wasm-bindgen"]) {
    const candidate = join(cargoBin, name);
    if (existsSync(candidate)) return candidate;
  }
  return "wasm-bindgen";
}

run("cargo", [
  "build", "--profile", "wasm-release", "--target", "wasm32-unknown-unknown",
  "-p", "reader-wasm", "--manifest-path", join(repoDir, "Cargo.toml"),
]);

const wasmPath = join(repoDir, "target", "wasm32-unknown-unknown", "wasm-release", "reader_wasm.wasm");
if (!existsSync(wasmPath)) throw new Error(`missing wasm artifact: ${wasmPath}`);

mkdirSync(generatedDir, { recursive: true });
mkdirSync(publicDir, { recursive: true });
run(findWasmBindgen(), [wasmPath, "--target", "web", "--out-dir", generatedDir, "--out-name", "reader_core"]);

// Node treats extension-less .js as CommonJS; mirror the glue as .mjs/.d.mts
// so the Node test harness and the Next bundler share one source artifact.
copyFileSync(join(generatedDir, "reader_core.js"), join(generatedDir, "reader_core.mjs"));
copyFileSync(join(generatedDir, "reader_core.d.ts"), join(generatedDir, "reader_core.d.mts"));

// wasm-bindgen rewrites externref imports while emitting the glue; the browser
// must load that transformed binary, not the raw cargo artifact.
const transformed = join(generatedDir, "reader_core_bg.wasm");
const bytes = readFileSync(transformed);
const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 16);
const assetName = `reader_core.${hash}.wasm`;
for (const file of readdirSync(publicDir)) {
  if (file.endsWith(".wasm")) rmSync(join(publicDir, file));
}
copyFileSync(transformed, join(publicDir, assetName));

const wasmUrl = `/wasm/${assetName}`;
const header = `// Generated by scripts/build-wasm.mjs — do not edit or commit.\n`;
writeFileSync(
  join(generatedDir, "index.ts"),
  `${header}import init, { ReaderWasm } from "./reader_core.js";\n\nexport { init, ReaderWasm };\nexport const WASM_URL = "${wasmUrl}";\n\nexport async function loadReaderWasm(): Promise<{ ReaderWasm: typeof ReaderWasm }> {\n  await init({ module_or_path: WASM_URL });\n  return { ReaderWasm };\n}\n`,
);
writeFileSync(
  join(generatedDir, "index.mjs"),
  `${header}import init, { ReaderWasm } from "./reader_core.mjs";\n\nexport { init, ReaderWasm };\nexport const WASM_URL = "${wasmUrl}";\n\nexport async function loadReaderWasm() {\n  await init({ module_or_path: WASM_URL });\n  return { ReaderWasm };\n}\n`,
);
console.log(`wasm asset ${wasmUrl} (${bytes.length} bytes)`);
